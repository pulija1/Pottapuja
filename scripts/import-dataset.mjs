// Converts the grocery and recipe research dataset (JSON) into public/shared/dataset.js.
// Usage: node scripts/import-dataset.mjs path/to/indian-groceries-recipes.json
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(process.argv[2], "utf8"));
const items = Object.fromEntries(src.items.map((i) => [i.id, i]));
const WHO = { "baby-8m": "baby", "kid-4y-lunchbox": "kid" };
const UNIT = { each: "pcs" };

const recipes = src.recipes.map((r) => ({
  id: "ds-" + r.id,
  title: r.name,
  forWhom: WHO[r.audience] || "family",
  mealType: r.audience === "kid-4y-lunchbox" && r.mealType !== "snack" ? "lunchbox" : r.mealType,
  texture: r.audience === "baby-8m" ? "mashed" : "",
  prepMinutes: r.prepMinutes,
  ingredients: r.ingredients.map((i) => ({
    name: items[i.itemId]?.name.toLowerCase() || i.itemId,
    quantity: i.qty,
    unit: UNIT[i.unit] || i.unit,
    ...(i.note ? { note: i.note } : {}),
  })),
  steps: r.steps,
  notes: r.ageNotes || "",
  ...(r.familyFavorite ? { familyFavorite: true } : {}),
  ...(r.nutFree === false ? { nutFree: false } : {}),
  ...(r.nutFreeSwap ? { nutFreeSwap: r.nutFreeSwap.replace(/\s*\([a-z-]+\)/g, "") } : {}),
  source: "library",
}));

const names = src.items.map((i) => ({ id: i.id, name: i.name, names: i.names, category: i.category, icon: i.icon, allergens: i.allergens }));

writeFileSync(
  new URL("../public/shared/dataset.js", import.meta.url),
  `// Generated by scripts/import-dataset.mjs from the grocery and recipe research dataset (v${src.version}). Do not edit by hand.\n` +
  `export const DATASET_ITEMS = ${JSON.stringify(names)};\n` +
  `export const DATASET_RECIPES = ${JSON.stringify(recipes, null, 1)};\n`,
);
console.log(`${names.length} items, ${recipes.length} recipes`);
